"""Synchronous buck converter checks.

Two levels of evidence:

1. Closed-form design equations (duty cycle, inductor ripple, output ripple,
   input RMS current, set-point from the feedback divider).
2. A switched, open-loop SPICE transient (ideal-gated switches with the
   datasheet on-resistances, inductor DCR, capacitor ESR/ESL, input source
   impedance) run to steady state at the operating point. It independently
   confirms ripple and component currents, including the effect of losses.

Neither level models the controller's loop. Load-step response and stability
need the vendor's controller model; without it those checks are INCOMPLETE.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np

from .spice import run_netlist


# ── Closed-form ────────────────────────────────────────────────────────────

def duty(vin: float, vout: float) -> float:
    return vout / vin


def inductor_ripple_pp(vin: float, vout: float, l_h: float, fsw: float) -> float:
    """Peak-to-peak inductor ripple in CCM: (Vin - Vout) * D / (L * fsw)."""
    return (vin - vout) * duty(vin, vout) / (l_h * fsw)


def output_ripple_pp(i_ripple_pp: float, fsw: float, c_f: float, esr_ohm: float) -> dict:
    """Output ripple: capacitive term dI/(8 fsw C) and ESR term dI*ESR.

    The two are ~90° apart, so the true peak-to-peak lies between their root-
    sum-square and their sum; the sum is returned as the conservative bound.
    """
    v_c = i_ripple_pp / (8 * fsw * c_f)
    v_esr = i_ripple_pp * esr_ohm
    return {"capacitive": v_c, "esr": v_esr, "bound": v_c + v_esr,
            "rss": math.hypot(v_c, v_esr)}


def input_rms_current(iout: float, d: float, i_ripple_pp: float = 0.0) -> float:
    """Input-capacitor RMS current, including the inductor ripple term."""
    return math.sqrt(iout**2 * d * (1 - d) + d * i_ripple_pp**2 / 12)


def divider_vout(vref: float, r_top: float, r_bot: float) -> float:
    return vref * (1 + r_top / r_bot)


def divider_vout_range(vref_min, vref_max, r_top, r_bot, tol_top_pct, tol_bot_pct):
    lo = divider_vout(vref_min, r_top * (1 - tol_top_pct / 100), r_bot * (1 + tol_bot_pct / 100))
    hi = divider_vout(vref_max, r_top * (1 + tol_top_pct / 100), r_bot * (1 - tol_bot_pct / 100))
    return lo, hi


def interp_loglog(x, xs, ys):
    """Log-log interpolation in a monotonic table (e.g. RT -> fsw)."""
    order = np.argsort(xs)
    return float(np.exp(np.interp(np.log(x), np.log(np.asarray(xs)[order]),
                                  np.log(np.asarray(ys)[order]))))


# ── Switched SPICE testbench ───────────────────────────────────────────────

@dataclass
class CapBank:
    """``count`` identical parallel capacitors."""
    c_each_f: float
    count: int
    esr_each_ohm: float
    esl_each_h: float = 0.5e-9

    @property
    def c_total(self) -> float:
        return self.c_each_f * self.count


@dataclass
class BuckTestbench:
    vin: float
    vout_target: float
    iout: float
    fsw: float
    l_h: float
    l_dcr_ohm: float
    cout: list[CapBank]
    cin: list[CapBank]
    rds_hs_ohm: float
    rds_ls_ohm: float
    source_r_ohm: float = 0.05
    source_l_h: float = 100e-9
    dead_time_s: float = 10e-9
    # Switch-node capacitance (MOSFET Coss). Physically present, and needed for
    # the ideal-switch model to converge through each edge.
    c_sw_f: float = 300e-12
    cycles: int = 400
    measure_cycles: int = 20
    notes: list[str] = field(default_factory=list)

    def _bank_lines(self, name: str, node: str, banks: list[CapBank]) -> list[str]:
        lines = []
        for i, b in enumerate(banks):
            # n identical caps in parallel = one cap of n*C with ESR/n and ESL/n.
            c, esr, esl = b.c_total, b.esr_each_ohm / b.count, b.esl_each_h / b.count
            lines += [
                f"C{name}{i} {node} {name}{i}a {c:.6e} IC={{VCAP}}",
                f"R{name}{i} {name}{i}a {name}{i}b {esr:.6e}",
                f"L{name}{i} {name}{i}b 0 {esl:.6e}",
            ]
        return lines

    def netlist(self, d: float) -> str:
        t = 1 / self.fsw
        on = d * t - self.dead_time_s
        off = (1 - d) * t - 2 * self.dead_time_s
        tstop = self.cycles * t
        rload = self.vout_target / self.iout
        lines = [
            "* switched open-loop synchronous buck (generated by konnect_sim.buck)",
            f".param VCAP={self.vin}",
            f"VIN src 0 DC {self.vin}",
            f"RSRC src s1 {self.source_r_ohm}",
            f"LSRC s1 vin {self.source_l_h}",
        ]
        lines += self._bank_lines("IN", "vin", self.cin)
        lines += [
            # gate drives: HS on for `on`, LS on for `off`, dead time between
            f"VGH gh 0 PULSE(0 5 0 5n 5n {on:.6e} {t:.6e})",
            f"VGL gl 0 PULSE(0 5 {on + self.dead_time_s:.6e} 5n 5n {off:.6e} {t:.6e})",
            # Switches as gate-controlled conductances: 0 when the gate is low,
            # 1/RDS(on) when high, ramping linearly over the gate edge. Smoother
            # than ngspice's ideal S element, which fails to converge here.
            f"BHS vin sw I=V(vin,sw)*(1e-6 + min(max(V(gh)/5,0),1)/{self.rds_hs_ohm})",
            f"BLS sw 0 I=V(sw)*(1e-6 + min(max(V(gl)/5,0),1)/{self.rds_ls_ohm})",
            # body diode of the low-side FET carries current during dead time
            "DLS 0 sw DBODY",
            f"CSW sw 0 {self.c_sw_f:.6e}",
            f"L1 sw lx {self.l_h:.6e} IC={self.iout}",
            f"RDCR lx vout {self.l_dcr_ohm:.6e}",
        ]
        lines += [l.replace("{VCAP}", str(self.vout_target)) for l in self._bank_lines("OUT", "vout", self.cout)]
        lines += [
            f"RLOAD vout 0 {rload:.6e}",
            ".model DBODY D(IS=1e-12 N=1.05 RS=0.01)",
            f".tran {t / 400:.4e} {tstop:.6e} UIC",
            ".options method=gear reltol=1e-4",
            ".end",
        ]
        # Cin starts charged to Vin.
        return "\n".join(l.replace("{VCAP}", str(self.vin)) for l in lines)

    def run(self, d: float) -> dict:
        res = run_netlist(self.netlist(d))
        t = res["time"]
        t_end = t[-1]
        w = t >= t_end - self.measure_cycles / self.fsw
        vout, vin = res["vout"][w], res["vin"][w]
        il = None
        # inductor current = current through RDCR = (V(lx) - V(vout)) / DCR
        il = (res["lx"][w] - res["vout"][w]) / self.l_dcr_ohm
        # input capacitor current: source current minus switch current is not
        # directly a vector; take it from the Cin ESR resistors.
        icin = sum((res[f"in{i}a"][w] - res[f"in{i}b"][w]) / (b.esr_each_ohm / b.count)
                   for i, b in enumerate(self.cin))
        tw = t[w]
        def rms(x):
            return math.sqrt(np.trapezoid(x**2, tw) / (tw[-1] - tw[0]))
        return {
            "duty": d,
            "vout_avg": float(np.trapezoid(vout, tw) / (tw[-1] - tw[0])),
            "vout_pp": float(vout.max() - vout.min()),
            "vin_pp": float(vin.max() - vin.min()),
            "il_avg": float(np.trapezoid(il, tw) / (tw[-1] - tw[0])),
            "il_pp": float(il.max() - il.min()),
            "il_peak": float(il.max()),
            "icin_rms": rms(icin),
        }

    def run_at_setpoint(self, iterations: int = 3) -> dict:
        """Adjust duty so the average output equals ``vout_target`` (open loop),
        mimicking what the regulator's loop does in steady state."""
        d = self.vout_target / self.vin
        r = self.run(d)
        for _ in range(iterations):
            d *= self.vout_target / r["vout_avg"]
            r = self.run(d)
        return r
